  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_DAC_Init();
  MX_TIM6_Init();
  /* USER CODE BEGIN 2 */
  for (int i = 0; i < SINE_TABLE_SIZE; i++)
  {
      sine_wave[i] = (uint16_t)(
          2047.5f +
          2047.5f * sinf((2.0f * M_PI * i) / SINE_TABLE_SIZE)
      );
  }
  phase_increment =
      (uint32_t)(((uint64_t)output_freq << 32) / DAC_SAMPLE_RATE);

  for (int i = 0; i < DMA_BUFFER_SIZE; i++)
  {
      uint32_t index =
          ((uint64_t)phase_accumulator * SINE_TABLE_SIZE) >> 32;

      dac_buffer[i] = sine_wave[index];

      phase_accumulator += phase_increment;
  }
  HAL_DAC_Start_DMA(&hdac,
                    DAC_CHANNEL_1,
                    (uint32_t *)dac_buffer,
                    DMA_BUFFER_SIZE,
                    DAC_ALIGN_12B_R);

  HAL_TIM_Base_Start(&htim6);
  /* USER CODE END 2 */

  /* Initialize leds */
  BSP_LED_Init(LED2);

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	  HAL_ADC_Start(&hadc1);

	  if (HAL_ADC_PollForConversion(&hadc1, 100) == HAL_OK)
	  {
	      adc_value = HAL_ADC_GetValue(&hadc1);
	  }

	  HAL_ADC_Stop(&hadc1);

	  /* ADC: 0-4095 -> frequency: 1-10 kHz */
	  output_freq = 1000 + ((adc_value * 9000) / 4095);

	  /* DDS phase increment */
	  phase_increment =
	      (uint32_t)(((uint64_t)output_freq << 32) / DAC_SAMPLE_RATE);

	  HAL_Delay(20);

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
